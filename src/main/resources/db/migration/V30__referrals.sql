-- Referral program: every member gets a personal code; a friend who joins through it and buys a plan
-- qualifies; after 5 qualified friends the member earns a free Premium plan (a zero-price PAID order),
-- once per member. V30 because V29 is the idea pool (feature/idea-impact) -- merge that branch first.
create table referral_codes (
    user_id bigint not null references users (id),
    code varchar(12) not null,
    created_at timestamp(6) not null,
    primary key (user_id),
    constraint uk_referral_codes_code unique (code)
);

create table referrals (
    id bigint generated by default as identity,
    referrer_user_id bigint not null references users (id),
    referred_user_id bigint not null references users (id),
    created_at timestamp(6) not null,
    qualified_at timestamp(6),
    primary key (id),
    constraint uk_referrals_referred unique (referred_user_id)
);

create index idx_referrals_referrer on referrals (referrer_user_id);

create table referral_rewards (
    user_id bigint not null references users (id),
    order_id bigint not null references orders (id),
    granted_at timestamp(6) not null,
    primary key (user_id)
);
