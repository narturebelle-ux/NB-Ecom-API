-- Health details move out of the onboarding intake into their own section (product-owner decision,
-- 2026-10-30): written only with the HEALTH_DATA consent, every read/write audited.
create table health_profiles (
    id bigint generated by default as identity,
    user_id bigint not null unique references users (id),
    first_pregnancy boolean,
    multiples boolean,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table health_profile_risk_factors (
    health_profile_id bigint not null references health_profiles (id),
    risk_factor varchar(255) not null
);

-- Move every intake that holds any health detail. The answers were given at onboarding; using them for
-- recommendations still needs a HEALTH_DATA grant (HealthProfileService.forRecommendations).
insert into health_profiles (user_id, first_pregnancy, multiples, created_at, updated_at)
select i.user_id, i.first_pregnancy, i.multiples, i.created_at, i.updated_at
from onboarding_intakes i
where i.first_pregnancy is not null
   or i.multiples is not null
   or exists (select 1 from onboarding_intake_risk_factors r where r.intake_id = i.id);

insert into health_profile_risk_factors (health_profile_id, risk_factor)
select h.id, r.risk_factor
from onboarding_intake_risk_factors r
join onboarding_intakes i on i.id = r.intake_id
join health_profiles h on h.user_id = i.user_id;

drop table onboarding_intake_risk_factors;
alter table onboarding_intakes drop column first_pregnancy;
alter table onboarding_intakes drop column multiples;

