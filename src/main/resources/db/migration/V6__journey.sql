create table journeys (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    status varchar(255) not null,
    expected_delivery_date date,
    started_at timestamp(6) not null,
    closed_at timestamp(6),
    version bigint not null default 0,
    primary key (id)
);

-- At most one non-CLOSED journey per user (app-level check in JourneyService backs this up too).
create unique index uq_journeys_one_active_per_user on journeys (user_id) where status <> 'CLOSED';

create table journey_stage_events (
    id bigint generated by default as identity,
    journey_id bigint not null references journeys (id),
    from_status varchar(255),
    to_status varchar(255) not null,
    occurred_at timestamp(6) not null,
    actor_user_id bigint,
    source varchar(255) not null,
    primary key (id)
);

-- Backfill: one journey per existing user who has a legacy stage on file.
-- MONTH_3/6/9 -> PREGNANCY (carrying the legacy due_date as the EDD); BABY_CARE -> POSTPARTUM.
insert into journeys (user_id, status, expected_delivery_date, started_at, version)
select
    id,
    case stage
        when 'MONTH_3' then 'PREGNANCY'
        when 'MONTH_6' then 'PREGNANCY'
        when 'MONTH_9' then 'PREGNANCY'
        when 'BABY_CARE' then 'POSTPARTUM'
    end,
    case when stage in ('MONTH_3', 'MONTH_6', 'MONTH_9') then due_date else null end,
    now(),
    0
from users
where stage is not null;

insert into journey_stage_events (journey_id, from_status, to_status, occurred_at, source)
select id, null, status, started_at, 'SYSTEM'
from journeys;
