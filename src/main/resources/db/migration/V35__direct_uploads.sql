-- Provider documents and careers résumés move to S3 (owner, 12 Nov 2026), using the same browser-to-S3
-- upload as records (D48). upload_intents is the provider/careers counterpart of pending_uploads, kept
-- separate so such a file can never be saved as a health record. No file names or personal data here.

create table upload_intents (
    id bigint generated by default as identity,
    purpose varchar(40) not null,
    owner_user_id bigint references users (id),
    context_id bigint not null,
    context_key varchar(80),
    token_hash varchar(64),
    object_path varchar(1000) not null unique,
    storage_provider varchar(32) not null,
    kind varchar(32) not null,
    mime_type varchar(255) not null,
    declared_size_bytes bigint not null,
    multipart_upload_id varchar(1024),
    part_count integer,
    completed_at timestamp(6),
    expires_at timestamp(6) not null,
    created_at timestamp(6) not null,
    primary key (id)
);
create index idx_upload_intents_expires_at on upload_intents (expires_at);

