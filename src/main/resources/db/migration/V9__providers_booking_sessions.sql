-- Phase 3: Providers, booking & sessions.
-- payout_rates amounts below are placeholder figures per the product owner's note — the roadmap's
-- "payout rate (from config)" decision is explicitly deferred. Correct via a later migration once a
-- real rate exists, same precedent as V8's placeholder plan allocation numbers.

create table providers (
    id bigint generated by default as identity,
    user_id bigint not null unique references users (id),
    professional_type varchar(255) not null,
    display_name varchar(255),
    bio text,
    city varchar(255),
    status varchar(255) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null default 0,
    primary key (id)
);

create table provider_languages (
    provider_id bigint not null references providers (id),
    language varchar(255) not null
);

create table provider_credentials (
    id bigint generated by default as identity,
    provider_id bigint not null references providers (id),
    credential_type varchar(255) not null,
    document_reference varchar(500),
    issued_at date,
    expires_at date,
    verified_at timestamp(6),
    created_at timestamp(6) not null,
    primary key (id)
);

create table service_offerings (
    id bigint generated by default as identity,
    provider_id bigint not null references providers (id),
    name varchar(255) not null,
    description text,
    modality varchar(255) not null,
    duration_minutes integer not null,
    active boolean not null default true,
    created_at timestamp(6) not null,
    primary key (id)
);

create table provider_slots (
    id bigint generated by default as identity,
    provider_id bigint not null references providers (id),
    start_at timestamp(6) not null,
    end_at timestamp(6) not null,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    primary key (id)
);

create table bookings (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    provider_id bigint not null references providers (id),
    service_offering_id bigint not null references service_offerings (id),
    slot_id bigint not null references provider_slots (id),
    professional_type varchar(255) not null,
    status varchar(255) not null,
    scheduled_start timestamp(6) not null,
    scheduled_end timestamp(6) not null,
    provider_note text,
    note_locked_at timestamp(6),
    started_at timestamp(6),
    completed_at timestamp(6),
    no_show_at timestamp(6),
    cancelled_at timestamp(6),
    cancelled_by_user_id bigint,
    cancel_reason text,
    no_show_recorded_by_user_id bigint,
    no_show_reason text,
    rescheduled_from_booking_id bigint,
    consumed_entitlement_id bigint,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null default 0,
    primary key (id)
);

-- At most one active (non-cancelled/rescheduled) booking per slot — same partial-unique-index
-- pattern as uq_journeys_one_active_per_user (V6) / uq_plan_versions_one_active_per_plan (V8).
create unique index uq_bookings_one_active_per_slot on bookings (slot_id) where status not in ('CANCELLED', 'RESCHEDULED');

create table booking_note_amendments (
    id bigint generated by default as identity,
    booking_id bigint not null references bookings (id),
    previous_note text,
    new_note text not null,
    reason text,
    amended_by_user_id bigint not null,
    amended_at timestamp(6) not null,
    primary key (id)
);

create table session_feedback (
    id bigint generated by default as identity,
    booking_id bigint not null unique references bookings (id),
    user_id bigint not null,
    rating integer not null,
    comment text,
    created_at timestamp(6) not null,
    primary key (id)
);

create table payout_rates (
    id bigint generated by default as identity,
    professional_type varchar(255) not null unique,
    amount numeric(12,2) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table payouts (
    id bigint generated by default as identity,
    booking_id bigint not null unique references bookings (id),
    provider_id bigint not null references providers (id),
    amount numeric(12,2) not null,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    primary key (id)
);

