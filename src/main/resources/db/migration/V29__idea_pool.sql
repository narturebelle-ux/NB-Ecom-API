-- Idea pool: members post ideas in five categories and vote; votes from members with a paid order
-- count toward the implementation goal. Implemented ideas feature on the public Idea Impact section.
create table ideas (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    category varchar(255) not null check (category in
        ('CARE_AND_SESSIONS','NUTRITION_AND_WELLNESS','BABY_AND_POSTPARTUM','COMMUNITY','APP_EXPERIENCE')),
    title varchar(120) not null,
    description varchar(1500) not null,
    status varchar(255) not null check (status in ('OPEN','UNDER_REVIEW','IMPLEMENTED','DECLINED')),
    feature_consent boolean not null default false,
    impact_note varchar(1000),
    goal_reached_at timestamp(6),
    implemented_at timestamp(6),
    created_at timestamp(6) not null,
    primary key (id)
);

create table idea_votes (
    id bigint generated by default as identity,
    idea_id bigint not null references ideas (id),
    user_id bigint not null references users (id),
    created_at timestamp(6) not null,
    primary key (id),
    constraint uk_idea_votes_idea_user unique (idea_id, user_id)
);

create index idx_idea_votes_user on idea_votes (user_id);

-- The pool runs for the first few days only: turning this flag off closes submissions and voting.
insert into feature_flags (flag_key, enabled, description) values
    ('ideaPool', true, 'Idea pool: members submit ideas and vote (submissions and voting close when off)')
on conflict (flag_key) do nothing;
