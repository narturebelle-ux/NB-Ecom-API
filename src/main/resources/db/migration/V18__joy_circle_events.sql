create table community_events (
    id bigint generated by default as identity,
    title varchar(255) not null,
    description varchar(2000),
    host_name varchar(255) not null,
    host_bio varchar(1000),
    category varchar(255),
    starts_at timestamp(6) not null,
    ends_at timestamp(6) not null,
    modality varchar(255) not null,
    location varchar(255),
    join_url varchar(255),
    capacity integer,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    primary key (id)
);

create index idx_community_events_ends_at on community_events (ends_at);

create table community_event_rsvps (
    id bigint generated by default as identity,
    event_id bigint not null references community_events (id),
    user_id bigint not null references users (id),
    created_at timestamp(6) not null,
    primary key (id),
    unique (event_id, user_id)
);

create index idx_community_event_rsvps_user on community_event_rsvps (user_id);

