-- F9-S19 (D48, D49): files move from Supabase Storage to AWS S3 in Mumbai. Each record says where its
-- bytes live, so existing Supabase files keep working until they are moved. Videos get a removal date
-- that matches the S3 lifecycle rule. No file names or health data are added anywhere.
-- Numbered V34 because feature/money-care-side already uses V33.

alter table health_records add column storage_provider varchar(32) not null default 'SUPABASE';
alter table health_records add column kind varchar(32) not null default 'DOCUMENT';
alter table health_records add column removal_at timestamp(6);

create table pending_uploads (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    object_path varchar(1000) not null unique,
    storage_provider varchar(32) not null,
    kind varchar(32) not null,
    mime_type varchar(255) not null,
    declared_size_bytes bigint not null,
    multipart_upload_id varchar(1024),
    part_count integer,
    completed_at timestamp(6),
    expires_at timestamp(6) not null,
    created_at timestamp(6) not null,
    primary key (id)
);
create index idx_pending_uploads_user_id on pending_uploads (user_id);

-- The daily video job (F9-S19 items 12, 13). One row per thing it has done for a video, per removal
-- date: WARN_7 / WARN_1 (warnings), TRASHED, PURGED. The unique key makes each one happen once, even
-- if two API copies run the job together. A restored video has a new removal date, so it starts fresh.
create table video_retention_notices (
    id bigint generated by default as identity,
    record_id bigint not null references health_records (id),
    kind varchar(32) not null,
    cycle_removal_at timestamp(6) not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint uq_video_retention_notice unique (record_id, kind, cycle_removal_at)
);

-- A lease so only one API copy runs a scheduled job at a time. Plain rows rather than Postgres advisory
-- locks, so it behaves the same through the session pooler and in tests.
create table job_locks (
    name varchar(64) not null,
    locked_by varchar(64),
    locked_until timestamp(6) not null,
    primary key (name)
);
