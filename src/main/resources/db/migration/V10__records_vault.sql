-- Phase 4: Records vault & sharing. Metadata/sharing/access-log only — file bytes live in Supabase
-- Storage, never in this DB. record_access_events deliberately has no column for filename/mime/size/
-- category: "no document names or health data in logs" is enforced structurally here, not just by
-- convention.

create table health_records (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    category varchar(255) not null,
    original_file_name varchar(500) not null,
    mime_type varchar(255),
    size_bytes bigint,
    storage_bucket varchar(255) not null,
    storage_object_path varchar(1000) not null unique,
    status varchar(255) not null,
    scan_status varchar(255) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);
create index idx_health_records_user_id on health_records (user_id);

create table record_shares (
    id bigint generated by default as identity,
    record_id bigint not null references health_records (id),
    granted_by_user_id bigint not null,
    share_target_type varchar(255) not null,
    target_provider_id bigint references providers (id),
    target_booking_id bigint references bookings (id),
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    revoked_at timestamp(6),
    revoked_by_user_id bigint,
    primary key (id),
    constraint chk_record_shares_exactly_one_target check (
        (share_target_type = 'PROVIDER' and target_provider_id is not null and target_booking_id is null)
        or (share_target_type = 'BOOKING' and target_booking_id is not null and target_provider_id is null)
    )
);
create index idx_record_shares_record_id on record_shares (record_id);
create index idx_record_shares_target_provider_id on record_shares (target_provider_id);
create index idx_record_shares_target_booking_id on record_shares (target_booking_id);

create table record_access_events (
    id bigint generated by default as identity,
    record_id bigint not null references health_records (id),
    action varchar(255) not null,
    actor_user_id bigint not null,
    actor_relationship varchar(255) not null,
    share_id bigint references record_shares (id),
    occurred_at timestamp(6) not null,
    primary key (id)
);
create index idx_record_access_events_record_id on record_access_events (record_id);
