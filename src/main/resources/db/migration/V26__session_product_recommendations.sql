-- Products a professional recommends to a mother during a session; she sees them once it's COMPLETED.
create table session_product_recommendations (
    id bigint generated by default as identity,
    booking_id bigint not null references bookings (id),
    mother_user_id bigint not null references users (id),
    provider_id bigint not null references providers (id),
    product_id bigint not null references products (id),
    priority varchar(255) not null,
    note varchar(500),
    created_at timestamp(6) not null,
    primary key (id),
    unique (booking_id, product_id)
