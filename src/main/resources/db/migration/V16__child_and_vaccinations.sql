create table children (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    name varchar(255) not null,
    date_of_birth date not null,
    sex varchar(255),
    created_at timestamp(6) not null,
    primary key (id)
);

create index idx_children_user on children (user_id);

create table vaccine_schedule_versions (
    id bigint generated by default as identity,
    version integer not null,
    title varchar(255) not null,
    review_status varchar(255) not null,
    effective_at timestamp(6),
    active boolean not null default false,
    primary key (id)
);

create table vaccine_schedule_items (
    id bigint generated by default as identity,
    schedule_version_id bigint not null references vaccine_schedule_versions (id),
    vaccine_name varchar(255) not null,
    due_age_days integer not null,
    due_age_label varchar(255) not null,
    sort_order integer not null,
    primary key (id)
);

create table child_vaccinations (
    id bigint generated by default as identity,
    child_id bigint not null references children (id),
    schedule_item_id bigint not null references vaccine_schedule_items (id),
    given_at date not null,
    given_where varchar(255),
    recorded_at timestamp(6) not null,
    primary key (id),
    unique (child_id, schedule_item_id)
);

