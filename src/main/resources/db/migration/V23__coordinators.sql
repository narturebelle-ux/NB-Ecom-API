-- Onboarding coordinators ("Belle persons"): each call slot belongs to one, and users only see
-- slots from coordinators who speak one of their languages.
create table coordinators (
    id bigint generated by default as identity,
    display_name varchar(255) not null,
    photo_url varchar(255),
    bio varchar(1000),
    active boolean not null default true,
    created_at timestamp(6) not null,
    primary key (id)
);

create table coordinator_languages (
    coordinator_id bigint not null references coordinators (id),
    language varchar(255) not null
);

-- Null only on slots created before coordinators existed.
alter table onboarding_call_slots add column coordinator_id bigint references coordinators (id);
