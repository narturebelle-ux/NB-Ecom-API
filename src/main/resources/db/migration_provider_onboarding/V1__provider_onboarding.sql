-- Care professional onboarding. Everything lives in this service's own schema; public stays NB-Ecom-API's.
-- A public.providers row is created only when the Medical Reviewer approves, and stays off the directory
-- (status UNDER_REVIEW) until Operations sets the professional live.
create table provider_applications (
    id bigint generated by default as identity,
    user_id bigint not null,
    professional_type varchar(255) not null,
    status varchar(255) not null check (status in ('DRAFT','CHANGES_REQUESTED','OPERATIONS_REVIEW','MEDICAL_REVIEW','VERIFIED','ACTIVE','PAUSED','SUSPENDED','REJECTED','WITHDRAWN','CLOSED')),
    terms_version varchar(255) not null,
    terms_accepted_at timestamp(6) not null,
    registration_number varchar(255),
    licence_expires_on date,
    licence_lapsed boolean not null default false,
    submitted_at timestamp(6),
    last_activity_at timestamp(6) not null,
    reminder_count integer not null default 0,
    changes_requested_at timestamp(6),
    operations_reviewer_id bigint,
    operations_reviewed_at timestamp(6),
    medical_reviewer_id bigint,
    medical_reviewed_at timestamp(6),
    confirmed_experience_years integer,
    cleared_stages varchar(500),
    can_prescribe boolean not null default false,
    rejection_reason text,
    fraud_blocked boolean not null default false,
    reapply_after date,
    closed_at timestamp(6),
    purged_at timestamp(6),
    provider_id bigint,
    verified_at timestamp(6),
    recheck_required boolean not null default false,
    activated_at timestamp(6),
    agreement_version varchar(255),
    agreement_typed_name varchar(255),
    agreement_signed_at timestamp(6),
    training_passed_at timestamp(6),
    profile_confirmed_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null default 0,
    primary key (id)
);

-- At most one application in progress or approved per account; closed ones stay as history.
create unique index uq_provider_applications_one_open_per_user on provider_applications (user_id)
    where status not in ('REJECTED','WITHDRAWN','CLOSED');
create index idx_provider_applications_status on provider_applications (status);
create index idx_provider_applications_registration on provider_applications (registration_number);

create table application_answers (
    id bigint generated by default as identity,
    application_id bigint not null references provider_applications (id),
    question_key varchar(80) not null,
    answer_value text,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (application_id, question_key)
);

create table application_documents (
    id bigint generated by default as identity,
    application_id bigint not null references provider_applications (id),
    question_key varchar(80) not null,
    file_name varchar(255) not null,
    content_type varchar(100) not null,
    size_bytes integer not null,
    uploaded_at timestamp(6) not null,
    primary key (id),
    unique (application_id, question_key)
);

-- The file itself, in Postgres like careers résumés: 4 MB cap, and storage credentials aren't configured in prod.
create table application_document_contents (
    document_id bigint not null references application_documents (id),
    content bytea not null,
    primary key (document_id)
);

create table application_requested_changes (
    id bigint generated by default as identity,
    application_id bigint not null references provider_applications (id),
    question_key varchar(80) not null,
    note varchar(500),
    created_at timestamp(6) not null,
    primary key (id),
    unique (application_id, question_key)
);

-- Append-only: who decided what, at which stage, with the checklist they completed.
create table application_reviews (
    id bigint generated by default as identity,
    application_id bigint not null references provider_applications (id),
    stage varchar(255) not null check (stage in ('OPERATIONS','MEDICAL')),
    reviewer_user_id bigint not null,
    decision varchar(255) not null check (decision in ('PASS','APPROVE','CHANGES','REJECT')),
    reason text,
    checklist_json text,
    created_at timestamp(6) not null,
    primary key (id)
);

create table provider_bank_details (
    application_id bigint not null references provider_applications (id),
    account_holder_name varchar(160) not null,
    account_number_encrypted text not null,
    account_last4 varchar(4) not null,
    ifsc varchar(11) not null,
    account_type varchar(255) not null check (account_type in ('SAVINGS','CURRENT')),
    gst_registered boolean not null,
    gstin varchar(15),
    verification_status varchar(255) not null check (verification_status in ('PENDING','PASSED','FAILED')),
    verified_at timestamp(6),
    verified_by_user_id bigint,
    updated_at timestamp(6) not null,
    primary key (application_id)
);

create table profile_change_requests (
    id bigint generated by default as identity,
    application_id bigint not null references provider_applications (id),
    change_type varchar(255) not null check (change_type in ('PROFILE','NAME','LICENCE','BANK')),
    payload_encrypted text not null,
    status varchar(255) not null check (status in ('PENDING','APPROVED','REJECTED')),
    reviewer_user_id bigint,
    decision_reason text,
    created_at timestamp(6) not null,
    decided_at timestamp(6),
    primary key (id)
);

-- One row per reminder sent, so a re-run of the daily job can never email twice.
create table licence_reminders (
    id bigint generated by default as identity,
    application_id bigint not null references provider_applications (id),
    expires_on date not null,
    days_before integer not null,
    sent_at timestamp(6) not null,
    primary key (id),
    unique (application_id, expires_on, days_before)
);
