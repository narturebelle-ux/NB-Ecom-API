create table reminders (
    id bigint generated by default as identity,
    user_id bigint not null,
    type varchar(255) not null,
    title varchar(255) not null,
    body varchar(500) not null,
    due_at timestamp(6),
    source_type varchar(255) not null,
    source_id bigint not null,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    dismissed_at timestamp(6),
    primary key (id)
);

create index idx_reminders_user_status on reminders (user_id, status);

-- One active reminder per (user, source) -- re-running the generation job is safely idempotent.
create unique index uq_reminders_one_active_per_source on reminders (user_id, source_type, source_id) where status = 'ACTIVE';

create table notification_preferences (
    id bigint generated by default as identity,
    user_id bigint not null,
    channel varchar(255) not null,
    enabled boolean not null,
    primary key (id),
    unique (user_id, channel)
);

create table payment_reconciliation_flags (
    id bigint generated by default as identity,
    payment_id bigint not null unique references payments (id),
    flagged_at timestamp(6) not null,
    primary key (id)
);
