-- Careers (admin-posted roles + applications with a résumé) and the website ideas/feedback form.
-- Applications are personal data; how long to keep them is an open product-owner decision.
create table job_postings (
    id bigint generated by default as identity,
    title varchar(150) not null,
    team varchar(100),
    location varchar(120) not null,
    employment_type varchar(255) not null check (employment_type in ('FULL_TIME','PART_TIME','CONTRACT','INTERNSHIP')),
    work_mode varchar(255) not null check (work_mode in ('ONSITE','REMOTE','HYBRID')),
    summary varchar(500) not null,
    description varchar(10000) not null,
    status varchar(255) not null check (status in ('OPEN','CLOSED')),
    posted_at timestamp(6) not null,
    closed_at timestamp(6),
    primary key (id)
);

create table job_posting_requirements (
    job_id bigint not null references job_postings (id),
    position integer not null,
    requirement varchar(500),
    primary key (job_id, position)
);

create table job_applications (
    id bigint generated by default as identity,
    job_id bigint not null references job_postings (id),
    full_name varchar(120) not null,
    email varchar(254) not null,
    phone varchar(20) not null,
    location varchar(120),
    linkedin_url varchar(300),
    portfolio_url varchar(300),
    years_experience integer,
    cover_note varchar(3000),
    resume_file_name varchar(150) not null,
    resume_content_type varchar(100) not null,
    resume_size_bytes bigint not null,
    submitted_at timestamp(6) not null,
    admin_notified_at timestamp(6),
    primary key (id)
);

create index idx_job_applications_job on job_applications (job_id);

create table job_application_resumes (
    application_id bigint not null references job_applications (id),
    content bytea not null,
    primary key (application_id)
);

create table feedback_messages (
    id bigint generated by default as identity,
    user_id bigint,
    name varchar(120),
    email varchar(254),
    message varchar(3000) not null,
    rating integer check (rating between 1 and 5),
    page varchar(300),
    submitted_at timestamp(6) not null,
    admin_notified_at timestamp(6),
    primary key (id)
);
