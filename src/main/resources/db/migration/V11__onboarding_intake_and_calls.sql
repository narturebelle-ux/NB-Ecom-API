create table onboarding_intakes (
    id bigint generated by default as identity,
    user_id bigint not null unique references users (id),
    first_pregnancy boolean,
    multiples boolean,
    city varchar(255),
    language varchar(255),
    preferred_modality varchar(255),
    phone varchar(255),
    notes varchar(2000),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table onboarding_intake_risk_factors (
    intake_id bigint not null references onboarding_intakes (id),
    risk_factor varchar(255) not null
);

create table onboarding_intake_support_wanted (
    intake_id bigint not null references onboarding_intakes (id),
    support_wanted varchar(255) not null
);

create table onboarding_call_slots (
    id bigint generated by default as identity,
    start_at timestamp(6) not null,
    end_at timestamp(6) not null,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    primary key (id)
);

create index idx_onboarding_call_slots_status_start on onboarding_call_slots (status, start_at);

create table onboarding_calls (
    id bigint generated by default as identity,
    user_id bigint not null unique references users (id),
    slot_id bigint not null references onboarding_call_slots (id),
    scheduled_start timestamp(6) not null,
    scheduled_end timestamp(6) not null,
    created_at timestamp(6) not null,
    primary key (id)
);
