create table onboarding_documents (
    id bigint generated by default as identity,
    type varchar(255) not null,
    version integer not null,
    title varchar(255),
    body_markdown text,
    effective_at timestamp(6),
    active boolean not null default false,
    primary key (id)
);

create table onboarding_document_signatures (
    id bigint generated by default as identity,
    document_id bigint not null references onboarding_documents (id),
    user_id bigint not null references users (id),
    typed_name varchar(255) not null,
    signed_at timestamp(6) not null,
    emailed_at timestamp(6),
    primary key (id),
    unique (document_id, user_id)
);

create table onboarding_completions (
    id bigint generated by default as identity,
    user_id bigint not null unique references users (id),
    completed_at timestamp(6) not null,
    primary key (id)
);

