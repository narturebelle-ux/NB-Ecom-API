create table hospital_referrals (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    hospital_id bigint not null references hospital_partners (id),
    code varchar(255) not null unique,
    status varchar(255) not null,
    note varchar(1000),
    created_at timestamp(6) not null,
    confirmed_at timestamp(6),
    primary key (id)
);

create index idx_hospital_referrals_user on hospital_referrals (user_id);

-- At most one open referral per (user, hospital) -- backstops HospitalReferralService's idempotent create.
create unique index uq_hospital_referrals_one_open on hospital_referrals (user_id, hospital_id) where status = 'REQUESTED';
