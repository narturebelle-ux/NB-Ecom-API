-- Every email the Care API asks NB-Ecom-Mails-API to send. The row commits with the action that caused it, so a
-- crash or a sleeping Mails container can't lose the email. Addresses and text are cleared once sent.
create table outgoing_emails (
    id                    bigint generated by default as identity primary key,
    event_id              varchar(120) not null unique,
    event_type            varchar(80)  not null,
    kind                  varchar(20)  not null,
    user_id               bigint,
    to_address            varchar(320),
    reply_to              varchar(320),
    subject               text,
    body                  text,
    on_delivered          varchar(30),
    source_id             bigint,
    status                varchar(20)  not null,
    attempts              integer      not null default 0,
    last_attempt_at       timestamp,
    created_at            timestamp    not null,
    sent_at               timestamp
);
create index idx_outgoing_emails_pending on outgoing_emails (id) where status = 'PENDING';
