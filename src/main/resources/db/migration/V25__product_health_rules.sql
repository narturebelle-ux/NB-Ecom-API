-- Product tags (e.g. "high-sugar", "sugar-free") that health rules refer to.
create table product_tags (
    product_id bigint not null references products (id),
    tag varchar(255) not null
);

-- Reviewed-once rules mapping a risk factor to products to avoid or prefer. Only APPROVED rules apply.
create table product_health_rules (
    id bigint generated by default as identity,
    risk_factor varchar(255) not null,
    tag varchar(255) not null,
    effect varchar(255) not null,
    reason varchar(500) not null,
    status varchar(255) not null,
    created_by_user_id bigint not null references users (id),
    created_at timestamp(6) not null,
    reviewed_by_user_id bigint references users (id),
    reviewed_by_name varchar(255),
    reviewed_by_role varchar(255),
    reviewed_at timestamp(6),
    rejection_reason varchar(1000),
    primary key (id)
);

create index idx_product_health_rules_status_risk on product_health_rules (status, risk_factor);
