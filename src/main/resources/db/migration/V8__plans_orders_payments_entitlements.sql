-- Phase 2: Plans, checkout & entitlements.
-- Placeholder per-professional allocation, validity window and plan inclusions/exclusions copy per
-- the product owner's note — not the final "blueprint §5" numbers (that document isn't available as
-- a file). Correct via a later migration once the real numbers/copy exist. Prices/session totals
-- (Standard 9999/9, Care 14999/12, Premium 24999/16) are the only figures taken directly from
-- NARTUREBELLE_ROADMAP.md itself, not placeholders.

create table plans (
    id bigint generated by default as identity,
    code varchar(255) not null unique,
    name varchar(255) not null,
    display_order integer not null,
    primary key (id)
);

create table plan_versions (
    id bigint generated by default as identity,
    plan_id bigint not null references plans (id),
    version integer not null,
    active boolean not null default true,
    one_time_price numeric(12,2) not null,
    installment_total_price numeric(12,2) not null,
    installment_count integer not null,
    total_sessions integer not null,
    validity_days integer not null,
    effective_at timestamp(6) not null,
    primary key (id),
    unique (plan_id, version)
);

-- At most one active version per plan (mirrors uq_journeys_one_active_per_user from V6).
create unique index uq_plan_versions_one_active_per_plan on plan_versions (plan_id) where active = true;

create table plan_version_inclusions (
    plan_version_id bigint not null references plan_versions (id),
    inclusion varchar(1000) not null
);

create table plan_version_exclusions (
    plan_version_id bigint not null references plan_versions (id),
    exclusion varchar(1000) not null
);

create table plan_entitlements (
    id bigint generated by default as identity,
    plan_version_id bigint not null references plan_versions (id),
    professional_type varchar(255) not null,
    session_count integer not null,
    primary key (id)
);

create table orders (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    plan_version_id bigint not null references plan_versions (id),
    idempotency_key varchar(255) not null,
    request_fingerprint varchar(255) not null,
    status varchar(255) not null,
    payment_mode varchar(255) not null,
    price numeric(12,2) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null default 0,
    primary key (id),
    unique (user_id, idempotency_key)
);

create table installment_schedules (
    id bigint generated by default as identity,
    order_id bigint not null references orders (id),
    installment_number integer not null,
    amount numeric(12,2) not null,
    due_date date not null,
    primary key (id)
);

create table payments (
    id bigint generated by default as identity,
    order_id bigint not null references orders (id),
    provider varchar(255) not null,
    provider_payment_reference varchar(255) not null unique,
    status varchar(255) not null,
    amount numeric(12,2) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table payment_webhook_events (
    id bigint generated by default as identity,
    payment_id bigint not null references payments (id),
    provider_event_id varchar(255) not null unique,
    event_type varchar(255) not null,
    raw_payload text,
    processed_at timestamp(6) not null,
    primary key (id)
);

create table refunds (
    id bigint generated by default as identity,
    order_id bigint not null references orders (id),
    amount numeric(12,2) not null,
    reason text,
    admin_user_id bigint not null references users (id),
    created_at timestamp(6) not null,
    primary key (id)
);

create table entitlements (
    id bigint generated by default as identity,
    user_id bigint not null references users (id),
    order_id bigint not null references orders (id),
    professional_type varchar(255) not null,
    total_sessions integer not null,
    used_sessions integer not null default 0,
    expires_at timestamp(6) not null,
    created_at timestamp(6) not null,
    primary key (id),
    unique (order_id, professional_type)
);

